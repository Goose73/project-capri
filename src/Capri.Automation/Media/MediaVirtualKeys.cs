namespace Capri.Automation.Media;

/// <summary>
/// Windows virtual-key codes for media transport keys.
/// </summary>
public static class MediaVirtualKeys
{
    /// <summary>VK_MEDIA_NEXT_TRACK.</summary>
    public const int NextTrack = 0xB0;

    /// <summary>VK_MEDIA_PREV_TRACK.</summary>
    public const int PreviousTrack = 0xB1;

    /// <summary>VK_MEDIA_STOP.</summary>
    public const int Stop = 0xB2;

    /// <summary>VK_MEDIA_PLAY_PAUSE.</summary>
    public const int PlayPause = 0xB3;
}
